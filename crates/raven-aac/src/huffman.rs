//! The Huffman codebooks of ISO/IEC 14496-3, Tables 4.A.1 to 4.A.12.
//!
//! Twelve fixed tables, transcribed once and checked by the tests below: each
//! is a complete prefix code (its Kraft sum is exactly one), which is what a
//! mistyped entry almost never is. Entry `i` of a spectral book is the code
//! for the tuple whose index is `i`, in the index order of section 4.6.3.3:
//! the tuple's values, offset to be non-negative where the book is signed,
//! read as the digits of a number in base 3, 9, 8, 13 or 17.

/// One codebook: `codes[i]` is `lens[i]` bits long, right-aligned.
#[derive(Debug)]
pub(crate) struct Book {
    pub(crate) codes: &'static [u32],
    pub(crate) lens: &'static [u8],
}

