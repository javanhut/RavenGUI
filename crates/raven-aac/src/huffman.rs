#[cfg(test)]
mod tests {
    use super::*;

    fn check(book: &Book, size: usize) {
        assert_eq!(book.codes.len(), size);
        assert_eq!(book.lens.len(), size);
        // Complete: the Kraft sum is exactly one.
        let kraft: u64 = book.lens.iter().map(|&l| 1u64 << (32 - l)).sum();
        assert_eq!(kraft, 1u64 << 32);
        // Prefix-free: no code is the start of another.
        for (i, (&a, &la)) in book.codes.iter().zip(book.lens).enumerate() {
            assert!(a < 1 << la, "code {i} longer than its length");
            for (j, (&b, &lb)) in book.codes.iter().zip(book.lens).enumerate() {
                if i != j && la <= lb {
                    assert_ne!(b >> (lb - la), a, "code {i} is a prefix of code {j}");
                }
            }
        }
    }

    #[test]
    fn every_book_is_a_complete_prefix_code() {
        let sizes = [81, 81, 81, 81, 81, 81, 64, 64, 169, 169, 289];
        for (book, size) in SPECTRAL.iter().zip(sizes) {
            check(book, size);
        }
        check(&SCALEFACTORS, 121);
        // A scalefactor that does not change is the one-bit code.
        assert_eq!((SCALEFACTORS.codes[60], SCALEFACTORS.lens[60]), (0, 1));
    }
}
